import { describe, expect, it } from "vitest";
import { guOfPoint } from "../gu";

describe("guOfPoint — 서울 25구(정밀) + 전국 시군구(단순화본) 경계 판정", () => {
  it.each([
    ["서울시청", 37.5665, 126.978, "중구"], // 청계천 경계에서 300m — 단순화본이면 종로구로 새던 점
    ["삼성역", 37.5089, 127.0631, "강남구"],
    ["잠실역", 37.5133, 127.1001, "송파구"],
    ["홍대입구역", 37.5571, 126.9245, "마포구"],
    ["노원역", 37.6553, 127.0616, "노원구"],
  ])("서울 %s → %s", async (_, lat, lng, gu) => {
    expect(await guOfPoint({ lat, lng })).toBe(gu);
  });

  it.each([
    ["김포 고촌", 37.6, 126.77, "김포시(경기)"], // 시드의 표기와 같다
    ["해운대", 35.1631, 129.1635, "해운대구(부산)"],
    ["제주시", 33.5, 126.53, "제주시(제주)"],
    ["창원 진해", 35.15, 128.7, "창원시 진해구(경남)"], // 일반구는 띄어쓴다
    ["수원 팔달", 37.2789, 127.0175, "수원시 팔달구(경기)"],
    ["세종", 36.48, 127.26, "세종시(세종)"],
  ])("서울 밖 %s → %s", async (_, lat, lng, gu) => {
    expect(await guOfPoint({ lat, lng })).toBe(gu);
  });

  it("한국 밖(서해 바다·독도 동쪽)은 null", async () => {
    expect(await guOfPoint({ lat: 36.0, lng: 125.0 })).toBeNull();
    expect(await guOfPoint({ lat: 37.24, lng: 132.0 })).toBeNull();
  });
});
